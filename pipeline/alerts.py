"""Alerts and the weekly digest, delivered as GitHub issues (GitHub emails the owner) and,
optionally, to a Discord/Slack webhook. No extra accounts needed.

An alert with the same title as an open issue becomes a comment on it, not a duplicate.
"""

from __future__ import annotations

import contextlib
import json
import os
import urllib.request
from collections.abc import Callable
from typing import Any

API = "https://api.github.com"
Poster = Callable[[str, str, dict[str, Any] | None], Any]


def _github(method: str, path: str, body: dict[str, Any] | None) -> Any:  # pragma: no cover
    req = urllib.request.Request(
        f"{API}{path}", method=method, data=json.dumps(body).encode() if body else None,
        headers={"Authorization": f"Bearer {os.environ['GITHUB_TOKEN']}",
                 "Accept": "application/vnd.github+json", "Content-Type": "application/json"})
    with urllib.request.urlopen(req, timeout=30) as r:
        return json.loads(r.read() or b"null")


def _webhook(text: str) -> None:  # pragma: no cover
    url = os.environ.get("ALERT_WEBHOOK_URL")
    if not url:
        return
    body = json.dumps({"content": text[:1900], "text": text[:3000]}).encode()
    urllib.request.urlopen(urllib.request.Request(
        url, data=body, headers={"Content-Type": "application/json"}), timeout=15)


FOOTER = "\n\n---\n_Generated by the Cold Save pipeline_"


def notify(title: str, body: str, label: str = "alert", github: Poster | None = None) -> str:
    """Open (or comment on) a GitHub issue. Returns 'created', 'commented' or 'printed'."""
    from pipeline.config import pipeline_enabled

    repo = os.environ.get("GITHUB_REPOSITORY")
    if label == "alert" and not pipeline_enabled() and github is None:
        print(f"[{label} suppressed: pipeline disabled] {title}\n{body}")
        return "printed"
    if (not repo or not os.environ.get("GITHUB_TOKEN")) and github is None:
        print(f"[{label}] {title}\n{body}")
        return "printed"
    post = github or _github
    with contextlib.suppress(Exception):  # webhook is best-effort
        _webhook(f"**{title}**\n{body}")
    issues = post("GET", f"/repos/{repo}/issues?state=open&labels={label}&per_page=50", None)
    for issue in issues or []:
        if issue.get("title") == title:
            post("POST", f"/repos/{repo}/issues/{issue['number']}/comments",
                 {"body": body + FOOTER})
            return "commented"
    post("POST", f"/repos/{repo}/issues", {"title": title, "body": body + FOOTER,
                                           "labels": [label]})
    return "created"
